CREATE TABLE `CompanyAccessRequest` (
 `id` CHAR(36) NOT NULL,
 `name` VARCHAR(160) NOT NULL,
 `fullName` VARCHAR(160) NOT NULL,
 `email` VARCHAR(254) NOT NULL,
 `phone` VARCHAR(32) NOT NULL,
 `countryCode` CHAR(2) NOT NULL,
 `city` VARCHAR(120) NOT NULL,
 `address` VARCHAR(500) NOT NULL,
 `description` VARCHAR(2000) NULL,
 `status` VARCHAR(12) NOT NULL DEFAULT 'PENDING',
 `pendingEmail` VARCHAR(254) NULL,
 `companyId` CHAR(36) NULL,
 `reviewedById` CHAR(36) NULL,
 `reviewedAt` DATETIME(3) NULL,
 `reason` VARCHAR(500) NULL,
 `version` INT NOT NULL DEFAULT 1,
 `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `updatedAt` DATETIME(3) NOT NULL,
 PRIMARY KEY (`id`),
 UNIQUE INDEX `CompanyAccessRequest_pendingEmail_key` (`pendingEmail`),
 UNIQUE INDEX `CompanyAccessRequest_companyId_key` (`companyId`),
 INDEX `CompanyAccessRequest_status_createdAt_idx` (`status`, `createdAt`),
 CONSTRAINT `chk_company_request_status` CHECK (`status` IN ('PENDING','APPROVED','REJECTED')),
 CONSTRAINT `chk_company_request_version` CHECK (`version` > 0)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
